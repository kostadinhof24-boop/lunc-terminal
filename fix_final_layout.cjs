  "import { motion } from 'framer-motion';",
  "import { useQuery } from '@tanstack/react-query';",
  "import axios from 'axios';",
  "import { Flame, Coins, BarChart2, Activity } from 'lucide-react';",
  "import StatCard from './StatCard';",
  "import AnalyticsPanel from '@/features/analytics/components/AnalyticsPanel';",
  "import { TERRA_CLASSIC_CONFIG } from '@/config/chains';",
  "",
  "export default function DashboardClient() {",
  "  // Fetch Stats Réseau (Block height, Staked)",
  "  const { data: stats, isLoading } = useQuery({",
  "    queryKey: ['networkStats'],",
  "    queryFn: async () => {",
  "      const res = await axios.get('/api/network-stats');",
  "      return res.data.data;",
  "    },",
  "    refetchInterval: 60000,",
  "  });",
  "",
  "  // Fetch Total Burned directement depuis la LCD",
  "  const { data: burnData } = useQuery({",
  "    queryKey: ['totalBurnedLunc'],",
  "    queryFn: async () => {",
  "      const res = await axios.get(`${TERRA_CLASSIC_CONFIG.lcdUrl}/cosmos/bank/v1beta1/balances/terra1sk06e3dyexuq4shw77y4dtt0xpqkcjm974wu5w/by_denom?denom=uluna`);",
  "      return parseFloat(res.data.balance.amount) / 1_000_000;",
  "    }",
  "  });",
  "",
  "  const formatNumber = (num) => {",
  "    if (!num) return '0';",
  "    if (num >= 1_000_000_000_000) return (num / 1_000_000_000_000).toFixed(2) + 'T';",
  "    if (num >= 1_000_000_000) return (num / 1_000_000_000).toFixed(2) + 'B';",
  "    if (num >= 1_000_000) return (num / 1_000_000).toFixed(2) + 'M';",
  "    return num.toLocaleString();",
  "  };",
  "",
  "  return (",
  "    <main className='min-h-screen relative container mx-auto px-6 py-8 max-w-7xl'>",
  "      <motion.div initial={{ opacity: 0, y: -20 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.5, delay: 0.1 }} className='glass-card rounded-3xl p-8 mb-6'>",
  "        <h1 className='text-2xl font-bold'>Network Dashboard</h1>",
  "        <p className='text-galaxy-gray text-sm'>Analyse en temps réel de l'écosystème Terra Classic.</p>",
  "      </motion.div>",
  "",
  "      <div className='grid grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-4 mb-8'>",
  "        <StatCard icon={<Flame className='w-5 h-5 text-galaxy-red' />} title='Total Burned' value={formatNumber(burnData || 0)} sub='Adresse Burn' loading={isLoading} />",
  "        <StatCard icon={<Coins className='w-5 h-5 text-terra-yellow' />} title='Staked' value={isLoading ? '...' : formatNumber(stats?.staked || 0)} sub={isLoading ? '' : `${stats?.stakingRatio}% de la supply`} loading={isLoading} />",
  "        <StatCard icon={<BarChart2 className='w-5 h-5 text-galaxy-blue' />} title='Market Cap' value={isLoading ? '...' : '$592.4M'} sub='Source: CoinGecko' loading={isLoading} />",
