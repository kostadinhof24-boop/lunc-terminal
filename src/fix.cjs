w('src/features/wallet/services/wallet.service.ts', [
  "import { TERRA_CLASSIC_CONFIG } from '@/config/chains';",
  "",
  "export class WalletService {",
  "  constructor(controller, connected) {",
  "    this.controller = controller;",
  "    this.connected = connected;",
  "  }",
  "",
  "  getAddress() {",
  "    return this.connected ? Object.values(this.connected.addresses || {})[0] : undefined;",
  "  }",
  "",
  "  async executeTransaction(contractAddress, msg) {",
  "    if (!this.controller || !this.controller.post) throw new Error('Wallet non connecté');",
  "    const address = this.getAddress();",
  "    if (!address) throw new Error('Adresse non disponible');",
  "",
  "    const executeMsg = {",
  "      contract: contractAddress,",
  "      msg: Buffer.from(JSON.stringify(msg)).toString('base64'),",
  "      funds: [],",
  "    };",
  "",
  "    try {",
  "      const result = await this.controller.post({",
  "        msgs: [executeMsg],",
  "        gasAdjustment: '1.5',",
  "        chainID: TERRA_CLASSIC_CONFIG.chainId,",
  "      });",
  "      if (result && result.result && result.result.txhash) return result.result.txhash;",
  "      throw new Error('Transaction échouée');",
  "    } catch (err) { throw new Error(err.message || 'Erreur de broadcast'); }",
  "  }",
  "}"
].join('\n'));

