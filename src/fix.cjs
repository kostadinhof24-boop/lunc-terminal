  "      try { const r = await c.queryContractSmart(DFC_STAKING_CONTRACT, { get_unclaimed_rewards: { user_address: address } }); rewards = r.amount || '0'; } catch {}",
  "      try { const r = await c.queryContractSmart(DFC_STAKING_CONTRACT, { get_unclaimed_fees: { user_address: address } }); fees = r.amount || '0'; } catch {}",
  "      return { staked, rewards, fees };",
  "    } catch { return { staked: '0', rewards: '0', fees: '0' }; }",
  "  }",
